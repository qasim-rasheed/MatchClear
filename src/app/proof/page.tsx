import type { Metadata } from "next";
import { eq } from "drizzle-orm";
import { getDatabase } from "@/server/db";
import * as s from "@/server/db/schema";
import { usablePreview } from "@/server/evidence";
import { ProofWorkbench } from "@/components/proof-workbench";
import { ProofPreviews } from "@/components/proof-previews";
import benchmark from "../../../evidence/planner-benchmark.json";
import "./proof.css";

export const dynamic = "force-dynamic";
export const metadata: Metadata = {
  title: "MatchClear — See the evidence",
  description:
    "A working tournament example, saved YouCam previews and reproducible software evidence.",
};
export default async function ProofPage() {
  const ctx = getDatabase(),
    eventId = "stock-preview-example";
  const event = ctx.db.select().from(s.events).where(eq(s.events.id, eventId)).get();
  const workspaceHref = (tab?: string) => {
    const params = new URLSearchParams();
    if (event && !event.archived) params.set("event", eventId);
    if (tab) params.set("tab", tab);
    return params.size ? `/?${params}` : "/";
  };
  const examples =
    event && !event.archived
      ? ctx.db
          .select()
          .from(s.previews)
          .where(eq(s.previews.eventId, eventId))
          .all()
          .flatMap((p) => {
            const accepted = usablePreview(ctx, p.id, eventId, true);
            return accepted
              ? [
                  {
                    id: p.id,
                    name: accepted.design.name,
                    reference: p.referenceAssetId,
                    output: p.outputAssetId!,
                    reason: p.acceptanceReason,
                    version: p.apiVersion,
                  },
                ]
              : [];
          })
          .slice(0, 2)
      : [];

  return (
    <main className="proof-page" id="main">
      <nav className="proof-nav" aria-label="Evidence navigation">
        <a className="brand" href="/">
          MatchClear<span className="brand-dot">.</span>
        </a>
        <a className="button secondary" href={workspaceHref()}>
          Open the workspace ↗
        </a>
      </nav>
      <header className="proof-hero">
        <span className="eyebrow">FROM SHIRT PHOTOS TO AN ORDER DECISION</span>
        <h1>
          Check the matchups.
          <br />
          <em>Then choose the shirts.</em>
        </h1>
        <p>
          For a tournament organizer, choosing one team's shirt changes every match it plays.
          MatchClear connects on-person previews, recorded reviews and the complete order budget.
        </p>
        <div className="proof-hero-links">
          <a href="#real-previews">Inspect the YouCam evidence ↓</a>
          <a href="#verification">Read the measured software results ↓</a>
        </div>
      </header>
      <ProofWorkbench />
      <section className="proof-real" id="real-previews">
        <div className="proof-section-heading">
          <div>
            <span className="eyebrow">02 / THE YOUCAM CONTRIBUTION</span>
            <h2>Inspect the reference and the actual output.</h2>
          </div>
          <span className="proof-label">Saved live API results</span>
        </div>
        <p className="proof-intro">
          Product photos show the garment alone. YouCam Clothes V3 produces the on-person appearance
          for a reviewer to inspect: visible colour blocks, sleeves and pattern placement. The
          reviewer can reject a poor rendering before it influences a plan.
        </p>
        {examples.length ? (
          <ProofPreviews examples={examples} eventId={eventId} />
        ) : (
          <p className="form-note">
            No current permitted stock previews are available on this checkout. Open Preview Studio
            and supply your own permitted inputs. Illustrations above are not presented as API
            results.
          </p>
        )}
        <p className="proof-boundary">
          These saved examples use the same licensed adult stock model. They demonstrate the
          integration; they do not establish physical colour accuracy, field visibility or benefit
          for people with colour-vision deficiency. No new render is generated by this page.
        </p>
        <a className="text-button" href={workspaceHref("reviews")}>
          Open the actual review tools ↗
        </a>
      </section>
      <section className="proof-verification" id="verification">
        <div className="proof-section-heading">
          <div>
            <span className="eyebrow">03 / WHAT HAS BEEN MEASURED</span>
            <h2>Evidence with its limits attached.</h2>
          </div>
        </div>
        <div className="proof-metrics">
          <div>
            <strong>
              {benchmark.matchedIndependentEnumeration}/{benchmark.cases}
            </strong>
            <span>Synthetic cases matched independent exhaustive enumeration</span>
          </div>
          <div>
            <strong>{benchmark.invalidSelections}</strong>
            <span>Returned plans violating tested budget, locks or pair decisions</span>
          </div>
          <div>
            <strong>4 × 2</strong>
            <span>Teams × shirt options in each seeded benchmark case</span>
          </div>
        </div>
        <p>
          Seed {benchmark.seed}. {benchmark.feasibleCases} cases had a complete plan;{" "}
          {benchmark.infeasibleCases} had none within their supplied constraints. Both minimum cost
          and equal-cost change counts were checked. Reproduce with{" "}
          <code>npm run evidence:benchmark</code>.
        </p>
        <p className="proof-boundary">
          This benchmark checks software correctness. Its approvals and prices are synthetic. It
          does not measure real savings, user completion time or preview accuracy.
        </p>
        <div className="proof-claims">
          <div>
            <h3>Demonstrated</h3>
            <ul>
              <li>Real YouCam uploads, asynchronous tasks and saved outputs.</li>
              <li>Recorded decisions tied to exact images and shirt areas.</li>
              <li>A complete plan under supplied budget, stock and locks.</li>
              <li>A frozen seller brief with quantities, sources and charges.</li>
            </ul>
          </div>
          <div>
            <h3>Still unproven</h3>
            <ul>
              <li>Whether organizers make better decisions with on-person previews.</li>
              <li>Physical colour accuracy and recognition during a real match.</li>
              <li>Accessibility benefits across real players and spectators.</li>
              <li>Market demand, real purchasing savings or return reduction.</li>
            </ul>
          </div>
        </div>
      </section>
      <section className="proof-close">
        <h2>The output is a purchasing brief.</h2>
        <p>
          Confirm the selected shirts, sizes, quantities, prices and review notes. Give the seller a
          clear specification, with person photos excluded by default.
        </p>
        <a className="button" href={workspaceHref("brief")}>
          Open the saved order brief workflow →
        </a>
      </section>
      <footer className="proof-footer">
        Local working prototype · Solo developer testing · No participant-study claims · No
        deployment
      </footer>
    </main>
  );
}
